import streamlit as st
import numpy as np
import pandas as pd
from datetime import datetime
import statistical_evaluation as se
import mlefficacy_evaluation as me
import mia_evaluation as mia

# streamlit page config
st.set_page_config(
    page_title='Evaluate your synthetic data',
    layout='wide',
)

# hide streamlit style elements
st.markdown('''
    <style>
        .reportview-container {
            margin-top: -2em;
        }
        .stAppDeployButton {display:none;}
        footer {visibility: hidden;}
        #stDecoration {display:none;}
    </style>
''', unsafe_allow_html=True)

# prepare session state
if 'real_data' not in st.session_state:
    st.session_state.real_data = None
if 'synth_data' not in st.session_state:
    st.session_state.synth_data = None
if 'out_data' not in st.session_state:
    st.session_state.out_data = None
if 'start_button' not in st.session_state:
    st.session_state.start_button = False
if 'target_col' not in st.session_state:
    st.session_state.target_col = None
if 'project_name' not in st.session_state:
    st.session_state.project_name = ''
if 'ml_task' not in st.session_state:
    st.session_state.ml_task = 'Classification'
if 'evaluation_type' not in st.session_state:
    st.session_state.evaluation_type = ['Utility', 'Privacy']
if 'real_name' not in st.session_state:
    st.session_state.real_name = ''
if 'synth_name' not in st.session_state:
    st.session_state.synth_name = ''

if 'out_name' not in st.session_state:
    st.session_state.out_name = ''


# title
st.title('Evaluate your synthetic data')

# How to use
st.write('## How to use this framework')
with st.expander('Expand to see the instructions', expanded=False):
    st.markdown('''
1. **Input your data and project information**  
   Enter a project name, select the ML task (Classification or Regression), and choose the evaluation type (Utility, Privacy, or both).

2. **Upload your datasets**  
   Upload the following datasets in CSV format:
   - **Real dataset (In)**: The original data your generative model was trained on.  
   - **Synthetic dataset**: The synthetic data generated by your generative model.  
   - **Reference dataset (Out)**: Only needed for privacy evaluation. This is the data that was **NOT** used to train the generative model. It will be used to evaluate the privacy of the synthetic data.

3. **Start Evaluation**  
   Once all required information and data have been provided, the Start button will appear. Click the 'Start Evaluation' button to begin the evaluation process. The framework will then perform statistical, ML efficacy, and privacy evaluations based on your inputs.

4. **View Results**  
   After the evaluation is complete, you will see the results for statistical evaluation, ML efficacy evaluation, and privacy evaluation. The total score is calculated as the mean of all evaluation scores.

5. **Reset**  
   If you want to start over, click the "Reset" button to clear all inputs and results.
''')
st.divider()


# input container
input_container = st.empty()

if not st.session_state.start_button:
    with input_container.container():
        st.write('## Experiment Setup')
        st.write('### Input your data and project information')
        col1, col2, col3 = st.columns([2, 1, 1])
        with col1:
            st.text_input('Project Name', placeholder='Enter project name', key='project_name')
        with col2:
            st.segmented_control(
                label='ML Task',
                options=['Classification', 'Regression'],
                key='ml_task'
            )
        with col3:
            st.segmented_control(
                label='Evaluation Type',
                options=['Utility', 'Privacy'],
                key='evaluation_type',
                selection_mode='multi'
            )

        #if st.session_state.evaluation_type and 'Privacy' not in st.session_state.evaluation_type:
        #    st.session_state.out_data = 'not needed'

        upload_ready = False

        st.write('### Upload your data')
        if 'Privacy' not in st.session_state.evaluation_type:
            col1, col2, col3 = st.columns(3)
            with col1:
                real_data_csv = st.file_uploader('Upload real Data CSV', type=['csv'], key='real')
                if real_data_csv:
                    st.session_state.real_data = pd.read_csv(real_data_csv)
                    st.session_state.real_name = real_data_csv.name
            with col2:
                synth_data_csv = st.file_uploader('Upload synthetic Data CSV', type=['csv'], key='synth')
                if synth_data_csv:
                    st.session_state.synth_data = pd.read_csv(synth_data_csv)
                    st.session_state.synth_name = synth_data_csv.name
            with col3:
                if st.session_state.real_data is not None and st.session_state.synth_data is not None:
                    if st.session_state.ml_task == 'Classification':
                        cat_cols = st.session_state.real_data.select_dtypes(include=['object', 'category', 'bool']).columns.tolist()
                        bin_num = [col for col in st.session_state.real_data.select_dtypes(include=['number']).columns if st.session_state.real_data[col].nunique() == 2]
                        options = cat_cols + bin_num
                    else:
                        options = st.session_state.real_data.select_dtypes(include=['number', 'float64', 'int64']).columns.tolist()
                    st.selectbox('Target-Col for ML-Efficacy:', options=options, index=None, placeholder='Select target column', key='target_col')
                    upload_ready = True
        else:
            col1, col2, col3, col4 = st.columns(4)
            with col1:
                real_data_csv = st.file_uploader('Upload real Data CSV', type=['csv'], key='real')
                if real_data_csv:
                    st.session_state.real_data = pd.read_csv(real_data_csv)
                    st.session_state.real_name = real_data_csv.name
            with col2:
                synth_data_csv = st.file_uploader('Upload synthetic Data CSV', type=['csv'], key='synth')
                if synth_data_csv:
                    st.session_state.synth_data = pd.read_csv(synth_data_csv)
                    st.session_state.synth_name = synth_data_csv.name
            with col3:
                out_data_csv = st.file_uploader('Upload out Data CSV', type=['csv'], key='out')
                if out_data_csv:
                    st.session_state.out_data = pd.read_csv(out_data_csv)
                    st.session_state.out_name = out_data_csv.name
            with col4:
                if all([st.session_state.real_data is not None, st.session_state.synth_data is not None, st.session_state.out_data is not None]):
                    if st.session_state.ml_task == 'Classification':
                        cat_cols = st.session_state.real_data.select_dtypes(include=['object', 'category', 'bool']).columns.tolist()
                        bin_num = [col for col in st.session_state.real_data.select_dtypes(include=['number']).columns if st.session_state.real_data[col].nunique() == 2]
                        options = cat_cols + bin_num
                    else:
                        options = st.session_state.real_data.select_dtypes(include=['number', 'float64', 'int64']).columns.tolist()
                    st.selectbox('Target-Col for ML-Efficacy:', options=options, index=None, placeholder='Select target column', key='target_col')
                    upload_ready = True

        if upload_ready and st.session_state.target_col is not None:
            if st.button('Start Evaluation'):
                st.session_state.start_button = True
                input_container.empty()
                st.rerun()


if st.session_state.start_button == True:
    st.write('## Evaluation Results')
    # CV and seed setup for ML Efficacy
    if 'Regression' in st.session_state.ml_task:
        cv = 5
    else:
        cv = 3
    experiment_seed = 18425
    
    # Logs
    col1, col2, col3 = st.columns([2,3,2])
    with col1:
        st.write('### Project Information')
        subcol1, subcol2 = st.columns([1, 2])
        subcol1.write('**Project Name:**')
        subcol2.write(st.session_state.project_name)
        
        subcol1, subcol2 = st.columns([1, 2])
        subcol1.write('**ML Task:**')
        subcol2.write(st.session_state.ml_task)

        subcol1, subcol2 = st.columns([1, 2])
        subcol1.write('**Evaluation Type:**')
        if st.session_state.evaluation_type and 'Privacy' not in st.session_state.evaluation_type:
            subcol2.write('Utility')
        elif st.session_state.evaluation_type and 'Utility' not in st.session_state.evaluation_type:
            subcol2.write('Privacy')
        else:
            subcol2.write('Utility and Privacy')

        subcol1, subcol2 = st.columns([1, 2])
        subcol1.write('**Date / Time:**')
        subcol2.write(str(datetime.now()))
    
    with col2:
        st.write('### Dataset Information')
        subcol1, subcol2, subcol3 = st.columns([1, 2, 1])
        subcol1.write('**Real Dataset:**')
        subcol2.write(st.session_state.real_name)
        subcol3.write(str(st.session_state.real_data.shape))

        subcol1, subcol2, subcol3 = st.columns([1, 2, 1])
        subcol1.write('**Synthetic Dataset:**')
        subcol2.write(st.session_state.synth_name)
        subcol3.write(str(st.session_state.synth_data.shape))

        if st.session_state.evaluation_type and 'Privacy' in st.session_state.evaluation_type:
            subcol1, subcol2, subcol3 = st.columns([1, 2, 1])
            subcol1.write('**Out Dataset:**')
            subcol2.write(st.session_state.out_name)
            if st.session_state.out_data is not None:
                subcol3.write(str(st.session_state.out_data.shape))

        subcol1, subcol2, subcol3 = st.columns([1, 2, 1])
        subcol1.write('**Target Column:**')
        subcol2.write(st.session_state.target_col)

    with col3:
        st.write('### Experiment Information')
        subcol1, subcol2 = st.columns([1, 1])
        subcol1.write('**CV:**')
        subcol2.write(str(cv))
        subcol1, subcol2 = st.columns([1, 1])
        subcol1.write('**Experiment Seed:**')
        subcol2.write(str(experiment_seed))

    # reset button
    if st.button('Reset', type='primary'):
        for key in list(st.session_state.keys()):
            del st.session_state[key]
        st.rerun()

    st.divider()   


    # UTILITY EVALUATION
    eval_scores = []

    col1, col2, col3 = st.columns(3)

    if st.session_state.evaluation_type and 'Utility' in st.session_state.evaluation_type:
        # Statistical Evaluation
        with col1:

            st.write('### Statistical Evaluation')
            with st.spinner('Statistical Evaluation is running ...', show_time=True):
                # run statistical evaluation
                jsd_mean_result , wasserstein_mean_result, mean_corr_diff_result, total_mean_result = se.run_statistical_evaluation(st.session_state.real_data, st.session_state.synth_data)

                # save total mean result of statistical evaluation
                eval_scores.append(total_mean_result)

                st.metric(label='Mean Statistics', value= str(total_mean_result) + ' %', border=True, help='Mean of all statistics')
                subcol1, subcol2, subcol3 = st.columns(3)
                subcol1.metric(label='inverse JSD', value= str(jsd_mean_result) + ' %', border = True, label_visibility='visible', help='1 - Mean Jensen-Shannon-Divergence (categorical)')
                subcol2.metric(label='inverse WD', value=str(wasserstein_mean_result) + ' %', border = True, label_visibility='visible', help='1 - Mean Wasserstein Distance (numerical)')
                subcol3.metric(label='inverse Pairwise Correlation Diff', value=str(mean_corr_diff_result) + ' %', border = True, label_visibility='visible', help='1 - Mean Pairwise Correlation (categorical and numerical)')

            # ML Efficacy
            # CV and seed setup
            rng = np.random.RandomState(experiment_seed)
            cv_seeds = rng.randint(0, 1000000, size=cv)

        with col2:
            st.write('### ML Efficacy Evaluation') 
            with st.spinner('ML Efficacy is running ...', show_time=True): 
                # perform ml efficacy evaluation with classification ml task
                if st.session_state.ml_task == 'Classification': 
                    mlefficacy_acc, mlefficacy_f1 = me.run_mlefficacy_evaluation(st.session_state.real_data,
                                                                                st.session_state.synth_data,
                                                                                st.session_state.ml_task,
                                                                                st.session_state.target_col,
                                                                                cv,
                                                                                cv_seeds
                                                                                )
                    # save ml efficacy scores
                    mean_mlefficacy = (mlefficacy_acc + mlefficacy_f1) / 2
                    eval_scores.append(mean_mlefficacy)

                    # Display ML Efficacy Scores Classification
                    if 'Classification' in st.session_state.ml_task:
                        st.metric(label='Mean ML Efficacy', value= str(round(mean_mlefficacy,2)) + ' %', border=True, help='Mean of ML Efficacy')
                    subcol1, subcol2 = st.columns(2)
                    subcol1.metric(label='ML Efficacy Score (Accuracy)', value= str(mlefficacy_acc) + ' %', border=True, help='1 - Mean Accuracy Difference')
                    subcol2.metric(label='ML Efficacy Score (F1)', value= str(mlefficacy_f1) + ' %', border=True, help='1 - Mean F1 Difference')

                # perform ml efficacy evaluation with regression ml task
                else:
                    invalid_r2, mlefficacy_r2, valid_count, mlefficacyClipped = me.run_mlefficacy_evaluation(st.session_state.real_data,
                                                                st.session_state.synth_data,
                                                                st.session_state.ml_task,
                                                                st.session_state.target_col,
                                                                cv,
                                                                cv_seeds
                                                                )
                    
                    if mlefficacy_r2 is not None and invalid_r2 == False:

                        # save ml efficacy scores
                        eval_scores.append(mlefficacy_r2)

                        # Display ML Efficacy Scores
                        st.metric(label='ML Efficacy Score (R2)', value= str(mlefficacy_r2) + ' %', border=True, help='1 - Mean R2 Difference')
                        if mlefficacyClipped:
                            st.warning(f'The calculated R2 score is negative and has been clipped to 0.', icon='⚠️')

                    # some r2 scores were invalid, but not all --> result is available
                    elif invalid_r2 == True and mlefficacy_r2 is not None :
                        
                        # save ml efficacy scores
                        eval_scores.append(mlefficacy_r2)

                        # Display ML Efficacy Scores
                        st.metric(label='ML Efficacy Score (R2)', value= str(mlefficacy_r2) + ' %', border=True, help='1 - Mean R2 Difference')
                        st.warning(f'Some R2 values were excluded from the mean due to threshold violations. {valid_count}/{cv*2} were included.', icon='⚠️')
                        if mlefficacyClipped:
                            st.warning(f'The calculated R2 score is negative and has been clipped to 0.', icon='⚠️')

                    
                # all r2 scores were invalid 
                    else:
                        st.error('No valid R2 scores found. Reason: Threshold Violation', icon='🚨')

    # PRIVACY EVALUATION
    # Utility and Privacy Evaluation
    if st.session_state.evaluation_type and 'Privacy' in st.session_state.evaluation_type and 'Utility' in st.session_state.evaluation_type:
        with col3:
            st.write('### Privacy Evaluation')
            with st.spinner('Privacy Evaluation is running ...', show_time=True):
                epsilon, mia_result = mia.mia(st.session_state.real_data, st.session_state.out_data, st.session_state.synth_data, epsilon_percentile=0.01, distance_metric='euclidean')

                # save mia result
                eval_scores.append(mia_result)

                st.metric(label='Privacy Score', value= str(mia_result) + ' %', border=True, help='1 - Accuracy of MIA')
    
    # Privacy Evaluation only
    elif st.session_state.evaluation_type and 'Privacy' in st.session_state.evaluation_type and 'Utility' not in st.session_state.evaluation_type:
        with col1:
            st.write('### Privacy Evaluation')
            with st.spinner('Privacy Evaluation is running ...', show_time=True):
                    epsilon, mia_result = mia.mia(st.session_state.real_data, st.session_state.out_data, st.session_state.synth_data, epsilon_percentile=0.01, distance_metric='euclidean')

                    # save mia result
                    eval_scores.append(mia_result)

                    st.metric(label='Privacy Score', value= str(mia_result) + ' %', border=True, help='1 - Accuracy of MIA')

    # TOTAL SCORE
    st.divider()
    st.write('### Total Score')
    st.metric(label='Total Score', value=str(round(np.mean(eval_scores), 2)) + ' %', border=True, help='Mean of all evaluation scores')
